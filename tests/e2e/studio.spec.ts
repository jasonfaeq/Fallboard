import { expect, test } from '@playwright/test'

test('studio: focus mode gives the music room and keeps the playback position and loop', async ({ page }) => {
  await page.goto('/')
  await page.waitForFunction(() => !!window.__piano?.timeline)
  await page.getByRole('button', { name: 'Next bar', exact: true }).click()
  await page.keyboard.press('l')
  const before = await page.evaluate(() => ({ time: window.__piano.player.time, loop: window.__piano.player.loop }))
  const width = (await page.getByTestId('sheet').boundingBox())!.width
  await page.getByRole('button', { name: 'Focus mode', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Focus mode', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('complementary', { name: 'Workspace' })).toBeHidden()
  expect((await page.getByTestId('sheet').boundingBox())!.width).toBeGreaterThan(width + 150)
  expect(await page.evaluate(() => ({ time: window.__piano.player.time, loop: window.__piano.player.loop }))).toEqual(before)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('complementary', { name: 'Workspace' })).toBeVisible()
  await page.keyboard.press('z')
  await expect(page.getByRole('button', { name: 'Focus mode', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('z')
  await expect(page.getByRole('button', { name: 'Focus mode', exact: true })).toHaveAttribute('aria-pressed', 'false')
})

test('studio: direct import, library search, source filters and sorting work together', async ({ page }) => {
  await page.goto('/')
  await page.waitForFunction(() => !!window.__piano?.timeline)
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Import score', exact: true }).click()
  await (await chooser).setFiles('tests/fixtures/ode-repeat.musicxml')
  await expect(page.getByRole('heading', { name: 'Ode to Joy (test)' })).toBeVisible()
  await page.getByRole('button', { name: 'Scores', exact: true }).click()
  const library = page.getByRole('dialog', { name: 'Scores', exact: true })
  await expect(library.getByLabel('Search scores')).toBeFocused()
  await library.getByRole('button', { name: 'Collection', exact: true }).click()
  await expect(library.locator('.score-item')).toHaveCount(2)
  await library.getByLabel('Sort scores').selectOption('title')
  await expect(library.locator('.score-item').first()).toContainText('Prelude in C major')
  await library.getByLabel('Sort scores').selectOption('composer')
  await expect(library.locator('.score-item').first()).toContainText('Prelude in E minor')
  await library.getByLabel('Search scores').fill('chopin')
  await expect(library.locator('.score-item')).toHaveCount(1)
  await library.getByRole('button', { name: 'Imported', exact: true }).click()
  await expect(library.getByText('No imported score matches.')).toBeVisible()
  await library.getByLabel('Search scores').clear()
  await expect(library.locator('.score-item')).toHaveCount(1)
  await expect(library.locator('.score-item')).toContainText('Ode to Joy')
  await page.keyboard.press('Escape')
  await expect(library).toBeHidden()
  await expect(page.getByRole('button', { name: 'Scores', exact: true })).toBeFocused()
})

test('studio: library traps focus and keyboard activation does not trigger the player', async ({ page }) => {
  await page.goto('/')
  await page.waitForFunction(() => !!window.__piano?.timeline)
  await page.getByRole('button', { name: 'Scores', exact: true }).click()
  const library = page.getByRole('dialog', { name: 'Scores', exact: true })
  const close = library.getByRole('button', { name: 'Close scores' })
  await close.focus()
  await page.keyboard.press('Shift+Tab')
  await expect(library.getByRole('button', { name: 'Preview score', exact: true }).last()).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Space')
  await expect(library).toBeHidden()
  expect(await page.evaluate(() => window.__piano.player.playing)).toBe(false)
  const help = page.getByRole('button', { name: 'Keyboard shortcuts', exact: true })
  await help.click()
  const shortcuts = page.getByRole('dialog', { name: 'Keyboard shortcuts', exact: true })
  await expect(shortcuts.getByRole('button', { name: 'Close shortcuts' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(help).toBeFocused()
})

test('studio: keyboard seeking and resizing do not trigger global tempo shortcuts', async ({ page }) => {
  await page.goto('/')
  await page.waitForFunction(() => !!window.__piano?.timeline)
  const scrubber = page.getByRole('slider', { name: 'Position in the piece' })
  await scrubber.focus()
  await page.keyboard.press('ArrowRight')
  expect(await page.evaluate(() => window.__piano.player.time)).toBe(5)
  await page.keyboard.press('ArrowUp')
  expect(await page.evaluate(() => window.__piano.player.time)).toBe(10)
  expect(await page.evaluate(() => window.__piano.player.speed)).toBe(1)
  await page.keyboard.press('End')
  expect(await page.evaluate(() => window.__piano.player.time)).toBe(await page.evaluate(() => window.__piano.timeline!.end))
  await page.keyboard.press('Home')
  expect(await page.evaluate(() => window.__piano.player.time)).toBe(0)
  const divider = page.getByRole('separator', { name: 'Drag to resize the keys' })
  await divider.focus()
  await page.keyboard.press('ArrowUp')
  await expect(divider).toHaveAttribute('aria-valuenow', '47')
  expect(await page.evaluate(() => window.__piano.player.speed)).toBe(1)
  await page.reload()
  await page.waitForFunction(() => !!window.__piano?.timeline)
  await expect(divider).toHaveAttribute('aria-valuenow', '47')
})

test('studio: desktop, night, focus and library layouts stay within the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await page.waitForFunction(() => !!window.__piano?.timeline)
  await expect(page.getByTestId('sheet')).toHaveAttribute('data-systems', /[1-9]/)
  await page.screenshot({ path: '.qa/studio-desktop.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Night sheet', exact: true }).click()
  await expect(page.locator('.sheet-night')).toBeVisible()
  await page.screenshot({ path: '.qa/studio-night.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Night sheet', exact: true }).click()
  await page.getByRole('button', { name: 'Focus mode', exact: true }).click()
  // SheetView deliberately debounces panel resize rendering by 200 ms.
  await page.waitForTimeout(350)
  await page.screenshot({ path: '.qa/studio-focus.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  await page.waitForTimeout(350)
  await page.getByRole('button', { name: 'Scores', exact: true }).click()
  await page.screenshot({ path: '.qa/studio-library.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  const settings = (await page.getByRole('dialog', { name: 'Settings', exact: true }).boundingBox())!
  expect(settings.y).toBeGreaterThanOrEqual(0)
  expect(settings.y + settings.height).toBeLessThanOrEqual(1000)
  await page.screenshot({ path: '.qa/studio-settings.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  for (const [width, height] of [[1024, 768], [768, 900], [390, 844]]) {
    await page.setViewportSize({ width, height })
    await page.waitForTimeout(350)
    await expect(page.getByRole('button', { name: 'Play', exact: true })).toBeVisible()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), { message: `Layout fits ${width}px` }).toBe(true)
    for (const region of ['Sheet music', 'Keys']) {
      const box = (await page.getByRole('region', { name: region, exact: true }).boundingBox())!
      expect(box.height).toBeGreaterThan(90)
      expect(box.x).toBeGreaterThanOrEqual(0)
      expect(box.x + box.width).toBeLessThanOrEqual(width)
    }
    await page.getByRole('button', { name: 'Focus mode', exact: true }).click()
    const focusedSheet = (await page.getByTestId('sheet').boundingBox())!
    expect(focusedSheet.width).toBeGreaterThan(width - 70)
    await page.keyboard.press('Escape')
    await page.waitForTimeout(350)
    if (width === 390) {
      await page.screenshot({ path: '.qa/studio-mobile.png', animations: 'disabled' })
      await page.getByRole('button', { name: 'Settings', exact: true }).click()
      const box = (await page.getByRole('dialog', { name: 'Settings', exact: true }).boundingBox())!
      expect(box.x).toBeGreaterThanOrEqual(0)
      expect(box.x + box.width).toBeLessThanOrEqual(width)
      expect(box.y).toBeGreaterThanOrEqual(0)
      await page.screenshot({ path: '.qa/studio-mobile-settings.png', animations: 'disabled' })
    }
  }
})
