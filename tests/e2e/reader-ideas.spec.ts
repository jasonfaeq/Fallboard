import { expect, test, type Page } from '@playwright/test'
import { SessionTracker, type SessionSample } from '../../src/reader/sessions'

async function open(page: Page) {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.waitForFunction(() => !!window.__piano?.timeline && !!document.querySelector('[data-testid=sheet] svg'))
  return errors
}
async function importScore(page: Page, file: string, title: string) {
  await page.getByTestId('quick-import-input').setInputFiles(`tests/fixtures/${file}`)
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await page.waitForFunction(() => !!window.__piano.timeline)
}
const collectionCards = (page: Page) => page.getByRole('dialog', { name: 'Scores', exact: true }).locator('.score-list:not(.setlist-scores) .score-card')
const history = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('fallboard:sessions') ?? '{"history":[]}').history)

