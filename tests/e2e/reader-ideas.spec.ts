test('reader ideas: session clock excludes count-ins, paused previews and seek distance, and counts revisits', () => {
  const tracker = new SessionTracker()
  const base: SessionSample = { score: 'test', title: 'Test', composer: '', date: 1, audioTime: 0, active: false, position: 0, end: 100, speed: 2, repeats: 0, passage: { first: 0, label: 'Bars 1–4' } }
  tracker.sample(base) // count-in
  tracker.sample({ ...base, audioTime: 2, active: true })
  tracker.sample({ ...base, audioTime: 3, active: true, position: 2 })
  tracker.sample({ ...base, audioTime: 3.25, position: 2.5 }) // pause
  tracker.sample({ ...base, audioTime: 8.25, position: 90, speed: .75 }) // preview and seek while paused
  tracker.sample({ ...base, audioTime: 8.25, active: true, position: 90, speed: .75 })
  tracker.sample({ ...base, audioTime: 9.25, active: true, position: 0, speed: .75, repeats: 1 })
  const recap = tracker.finish('id', 2, 'finished')!
  expect(recap.seconds).toBe(2.25)
  expect(recap.changes).toBe(1)
  expect(recap.startSpeed).toBe(2)
  expect(recap.endSpeed).toBe(.75)
  expect(recap.passages).toEqual([{ first: 0, label: 'Bars 1–4', visits: 3 }])
})

test('reader ideas: session history records real playback, excludes previews, and persists', async ({ page }) => {
  const errors = await open(page)
  await importScore(page, 'context-study.musicxml', 'Context study')
  await page.getByLabel('Speed', { exact: true }).fill('200')
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__piano.player.state)).toBe('playing')
  await page.waitForTimeout(650)
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  // This fixture has a constant tempo and no seeks: score seconds / rate is the actual
  // listening interval, including any polling/automation delay after playback starts.
  const listened = await page.evaluate(() => window.__piano.player.time / window.__piano.player.speed)
  await page.getByRole('button', { name: 'Scores', exact: true }).click()
  await collectionCards(page).filter({ hasText: 'Prelude in C major' }).getByRole('button', { name: 'Preview score', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Stop preview', exact: true })).toBeVisible()
  await page.waitForTimeout(1300)
  await page.keyboard.press('Escape')
  await page.getByLabel('Speed', { exact: true }).fill('125')
  await page.getByRole('button', { name: 'Sessions', exact: true }).click()
  const sessions = page.getByRole('dialog', { name: 'Session history', exact: true })
  await sessions.getByRole('button', { name: 'Finish session', exact: true }).click()
  const saved = await history(page)
  expect(saved).toHaveLength(1)
  expect(saved[0].seconds).toBeGreaterThan(.5)
  expect(Math.abs(saved[0].seconds - listened)).toBeLessThan(.15)
  expect(saved[0]).toMatchObject({ reason: 'finished', startSpeed: 2, endSpeed: 1.25, changes: 1 })
  await expect(sessions.locator('.session-list')).toContainText('Context study')
  await page.screenshot({ path: '.qa/reader-sessions-1440.png', animations: 'disabled' })
  await page.reload()
  await page.waitForFunction(() => !!window.__piano?.timeline)
  await page.getByRole('button', { name: 'Sessions', exact: true }).click()
  await expect(sessions.locator('.session-list > li')).toHaveCount(1)
  expect(errors).toEqual([])
})

