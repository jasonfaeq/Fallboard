test('listening room: hidden tabs and browsing hold the countdown; no-pause is remembered without restoring autoplay', async ({ page }) => {
  const errors = await open(page)
  await smallSetlist(page)
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')) })
  await page.waitForTimeout(500)
  await page.evaluate(() => { delete (document as unknown as { hidden?: boolean }).hidden; document.dispatchEvent(new Event('visibilitychange')) })
  await expect(room(page).locator('.listening-status')).toHaveText('A moment, held for you')
  await room(page).getByRole('button', { name: 'Scores', exact: true }).click()
  await library(page).locator('.score-list:not(.setlist-scores) .score-card').filter({ hasText: 'Prelude in C major' }).getByRole('button', { name: 'Preview score', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__piano.engine.piano?.activeVoices ?? 0)).toBeGreaterThan(0)
  await page.keyboard.press('Escape')
  await expect(room(page)).toBeVisible()
  expect((await playerState(page)).playing).toBe(false)
  await room(page).getByLabel('Breathing space', { exact: true }).selectOption('0')
  await room(page).getByRole('button', { name: 'Resume countdown', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__piano.player.state)).toBe('playing')
  await page.reload()
  await page.waitForFunction(() => !!window.__piano?.timeline)
  await expect(room(page)).toHaveCount(0)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('piano-trainer:prefs')!).listeningGap)).toBe(0)
  expect((await playerState(page)).playing).toBe(false)
  expect(errors).toEqual([])
})

test('listening room: sleeve, title cards and controls fit desktop and compact screens', async ({ page }) => {
  const errors = await open(page)
  await setlist(page, ['Prelude in C major', 'Prelude in E minor'], 'When the day slows down')
  await library(page).getByRole('button', { name: 'Listening room', exact: true }).click()
  await room(page).getByRole('button', { name: 'Hold countdown', exact: true }).click()
  for (const [width, height] of [[1440, 1000], [1024, 768], [768, 900], [390, 844], [320, 740]]) {
    await page.setViewportSize({ width, height })
    await room(page).evaluate(el => { el.scrollTop = 0 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), { message: `Listening room fits ${width}px` }).toBe(true)
    const bounds = (await room(page).boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
    for (const label of ['Back to score', 'Start now', 'Resume countdown']) {
      const button = room(page).getByRole('button', { name: label, exact: true })
      await button.scrollIntoViewIfNeeded()
      expect(await button.evaluate(el => { const r = el.getBoundingClientRect(); return document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)?.closest('button') === el })).toBe(true)
    }
    await room(page).evaluate(el => { el.scrollTop = 0 })
    await page.screenshot({ path: `.qa/listening-room-${width}.png`, animations: 'disabled' })
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(room(page).locator('.listening-title-card')).toHaveCSS('animation-name', 'none')
  expect(errors).toEqual([])
})
