import { expect, test, type Page } from '@playwright/test'
import { ListeningBreak } from '../../src/reader/listening'

async function open(page: Page) {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    if (!localStorage.getItem('piano-trainer:prefs')) localStorage.setItem('piano-trainer:prefs', JSON.stringify({ countIn: false, listeningGap: 6 }))
  })
  await page.goto('/')
  await page.waitForFunction(() => !!window.__piano?.timeline && !!document.querySelector('[data-testid=sheet] svg'))
  return errors
}
const room = (page: Page) => page.getByRole('region', { name: 'Listening room', exact: true })
const library = (page: Page) => page.getByRole('dialog', { name: 'Scores', exact: true })
async function setlist(page: Page, titles: string[], name = 'A quiet evening') {
  await page.getByRole('button', { name: 'Scores', exact: true }).click()
  const shelf = library(page)
  await shelf.locator('summary').click()
  await shelf.getByLabel('New setlist name', { exact: true }).fill(name)
  await shelf.getByRole('button', { name: 'Create setlist', exact: true }).click()
  for (const title of titles) await shelf.locator('.score-list:not(.setlist-scores) .score-card').filter({ hasText: title }).getByRole('button', { name: 'Add score to setlist', exact: true }).click()
}
async function smallSetlist(page: Page) {
  for (const [file, title] of [['context-study.musicxml', 'Context study'], ['ode-repeat.musicxml', 'Ode to Joy (test)']]) {
    await page.getByTestId('quick-import-input').setInputFiles(`tests/fixtures/${file}`)
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await page.waitForFunction(() => !!window.__piano.timeline)
    await page.getByLabel('Speed', { exact: true }).fill('200')
    if (file === 'context-study.musicxml') await page.keyboard.press('l')
  }
  await setlist(page, ['Context study', 'Ode to Joy (test)'])
  await library(page).getByRole('button', { name: 'Listening room', exact: true }).click()
  await expect(room(page)).toBeVisible()
  await expect(room(page).getByRole('button', { name: 'Hold countdown', exact: true })).toBeEnabled()
}
const playerState = (page: Page) => page.evaluate(() => ({ playing: window.__piano.player.playing, time: window.__piano.player.time }))

test('listening room: the break clock excludes loading, holds and suspended time, and can cancel or skip', () => {
  const gap = new ListeningBreak()
  gap.start(3)
  expect(gap.tick(10, false)).toBe(false)
  expect(gap.tick(20, true)).toBe(false)
  gap.tick(21, true)
  expect(gap.remaining).toBe(2)
  gap.hold(21.5)
  gap.tick(100, true)
  expect(gap.remaining).toBe(1.5)
  gap.resume()
  gap.tick(101, true)
  gap.tick(102, false)
  gap.tick(200, true)
  expect(gap.remaining).toBe(1.5)
  expect(gap.tick(201.5, true)).toBe(true)
  gap.hold(201.5); gap.change(0)
  expect(gap.tick(300, true)).toBe(false)
  gap.resume()
  expect(gap.tick(301, true)).toBe(true)
  gap.cancel()
  expect(gap.pending).toBe(false)
  expect(gap.tick(500, true)).toBe(false)
})

test('listening room: title cards hold, start early and retain score settings', async ({ page }) => {
  const errors = await open(page)
  await smallSetlist(page)
  const listening = room(page)
  await expect(listening.getByRole('heading', { name: 'Context study', exact: true })).toBeVisible()
  await expect(listening.locator('.listening-next')).toContainText('Ode to Joy (test)')
  await expect(listening.locator('.listening-position > span').last()).toHaveText('0:04')
  await listening.getByRole('button', { name: 'Hold countdown', exact: true }).click()
  await listening.getByLabel('Breathing space', { exact: true }).selectOption('10')
  await page.waitForTimeout(600)
  expect(await playerState(page)).toEqual({ playing: false, time: 0 })
  expect(await page.evaluate(() => window.__piano.engine.piano?.activeVoices ?? 0)).toBe(0)
  await expect(listening.locator('.listening-status')).toHaveText('A moment, held for you')
  await listening.getByRole('button', { name: 'Start now', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__piano.player.state)).toBe('playing')
  expect(await page.evaluate(() => window.__piano.player.speed)).toBe(2)
  expect(await page.evaluate(() => window.__piano.player.loop)).toBeNull()
  expect(await page.evaluate(() => {
    const id = JSON.parse(localStorage.getItem('piano-trainer:prefs')!).lastScore
    return JSON.parse(localStorage.getItem(`piano-trainer:score:${id}`)!).loop
  })).toEqual([0, 0])
  await listening.getByRole('button', { name: 'Back to score', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Sheet music', exact: true })).toBeVisible()
  const beforeReturn = await page.evaluate(() => window.__piano.player.time)
  await expect.poll(() => page.evaluate(() => window.__piano.player.time)).toBeGreaterThan(beforeReturn + .15)
  await page.getByRole('button', { name: 'Listening room', exact: true }).click()
  await listening.getByRole('button', { name: 'Pause listening', exact: true }).click()
  const paused = await playerState(page)
  await page.waitForTimeout(250)
  expect(await playerState(page)).toEqual(paused)
  await listening.getByRole('button', { name: 'Next setlist piece', exact: true }).click()
  await expect(listening.getByRole('heading', { name: 'Ode to Joy (test)', exact: true })).toBeVisible()
  await expect(listening.getByRole('button', { name: 'Hold countdown', exact: true })).toBeEnabled()
  expect(await playerState(page)).toEqual({ playing: false, time: 0 })
  await listening.getByRole('button', { name: 'End setlist', exact: true }).click()
  await expect(listening).toHaveCount(0)
  await page.waitForTimeout(400)
  expect((await playerState(page)).playing).toBe(false)
  expect(errors).toEqual([])
})

test('listening room: automatic transitions leave real breathing space and save music-only recaps, then finish and replay', async ({ page }) => {
  const errors = await open(page)
  await smallSetlist(page)
  const listening = room(page)
  await listening.getByLabel('Breathing space', { exact: true }).selectOption('3')
  await listening.getByRole('button', { name: 'Start now', exact: true }).click()
  await expect(listening.getByRole('heading', { name: 'Ode to Joy (test)', exact: true })).toBeVisible({ timeout: 12000 })
  await expect(listening.getByRole('button', { name: 'Hold countdown', exact: true })).toBeEnabled()
  const since = await page.evaluate(() => window.__piano.engine.context!.currentTime)
  await page.waitForTimeout(750)
  expect(await playerState(page)).toEqual({ playing: false, time: 0 })
  await expect.poll(() => page.evaluate(() => window.__piano.player.state)).toBe('playing')
  expect(await page.evaluate(() => window.__piano.engine.context!.currentTime) - since).toBeGreaterThan(2.5)
  await expect(listening.locator('.listening-status')).toHaveText('Setlist finished', { timeout: 12000 })
  expect((await playerState(page)).playing).toBe(false)
  const history = await page.evaluate(() => JSON.parse(localStorage.getItem('fallboard:sessions')!).history)
  expect(history).toHaveLength(2)
  expect(history.map((item: { reason: string }) => item.reason)).toEqual(['completed', 'completed'])
  expect(history[0].seconds).toBeGreaterThan(5.7)
  expect(history[0].seconds).toBeLessThan(6.5)
  expect(history[1].seconds).toBeGreaterThan(3.7)
  expect(history[1].seconds).toBeLessThan(4.5)
  await listening.getByRole('button', { name: 'View sessions', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Session history', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await listening.getByRole('button', { name: 'Replay setlist', exact: true }).click()
  await expect(listening.getByRole('heading', { name: 'Context study', exact: true })).toBeVisible()
  await listening.getByRole('button', { name: 'End setlist', exact: true }).click()
  expect(errors).toEqual([])
})

