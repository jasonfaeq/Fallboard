import { expect, test, type Page } from '@playwright/test'

async function open(page: Page) {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.waitForFunction(() => !!window.__piano?.timeline && !!document.querySelector('[data-testid=sheet] svg'))
  return errors
}
async function ode(page: Page) {
  await page.getByTestId('quick-import-input').setInputFiles('tests/fixtures/ode-repeat.musicxml')
  await page.waitForFunction(() => window.__piano.timeline?.sounds.length === 30)
}
const loop = (page: Page) => page.evaluate(() => window.__piano.player.loop)

test('performance: the stage keeps the player and restores the reading layout', async ({ page }) => {
  const errors = await open(page)
  await page.getByRole('button', { name: 'Next bar', exact: true }).click()
  await page.keyboard.press('l')
  await page.getByLabel('Speed', { exact: true }).fill('75')
  const before = await page.evaluate(() => ({ time: window.__piano.player.time, loop: window.__piano.player.loop, speed: window.__piano.player.speed }))
  await page.getByRole('button', { name: 'Performance view', exact: true }).click()
  await expect(page.locator('.app')).toHaveClass(/is-performance/)
  await expect(page.getByRole('region', { name: 'Sheet music', exact: true })).toBeHidden()
  await expect(page.getByRole('img', { name: 'Piano keyboard' })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('piano-trainer:prefs')!).view)).toBe('both')
  expect(await page.evaluate(() => ({ time: window.__piano.player.time, loop: window.__piano.player.loop, speed: window.__piano.player.speed }))).toEqual(before)
  await page.getByRole('button', { name: 'Passage map', exact: true }).click()
  const map = page.getByRole('complementary', { name: 'Passage map', exact: true })
  // Short loops can be narrower than a pointer target. Both handles must remain reachable.
  for (const edge of ['start', 'end']) {
    const handle = map.getByRole('button', { name: `Loop ${edge} boundary`, exact: true })
    expect(await handle.evaluate((element) => {
      const box = element.getBoundingClientRect()
      return document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2)?.closest('button') === element
    })).toBe(true)
  }
  await map.getByRole('button', { name: 'Close passage map', exact: true }).click()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.locator('.app')).toHaveClass(/is-performance/)
  await expect(page.getByRole('dialog', { name: 'Settings', exact: true })).toBeHidden()
  await page.keyboard.press('p')
  await expect(page.getByRole('region', { name: 'Sheet music', exact: true })).toBeVisible()
  expect(await page.evaluate(() => ({ time: window.__piano.player.time, loop: window.__piano.player.loop, speed: window.__piano.player.speed }))).toEqual(before)
  expect(errors).toEqual([])
})

test('performance: idle controls fade while music keeps playing, and pointer or keyboard reveals them', async ({ page }) => {
  await open(page)
  await page.keyboard.press('p')
  await page.getByRole('button', { name: 'Count-in', exact: true }).click()
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await page.evaluate(() => (document.activeElement as HTMLElement)?.blur())
  await expect.poll(() => page.evaluate(() => window.__piano.player.time)).toBeGreaterThan(.1)
  await expect(page.locator('.app')).toHaveClass(/controls-hidden/, { timeout: 6000 })
  const at = await page.evaluate(() => window.__piano.player.time)
  await expect.poll(() => page.evaluate(() => window.__piano.player.time)).toBeGreaterThan(at + .2)
  expect(await page.evaluate(() => window.__piano.engine.piano!.activeVoices)).toBeGreaterThan(0)
  await page.mouse.move(50, 50)
  await expect(page.locator('.app')).not.toHaveClass(/controls-hidden/)
  await expect(page.locator('.app')).toHaveClass(/controls-hidden/, { timeout: 6000 })
  await page.keyboard.press('Tab')
  await expect(page.locator('.app')).not.toHaveClass(/controls-hidden/)
  await page.keyboard.press(' ')
  expect(await page.evaluate(() => window.__piano.player.playing)).toBe(false)
})

test('performance: passage selection, repeat passes, loop handles and saved names stay aligned', async ({ page }) => {
  const errors = await open(page)
  await ode(page)
  await page.keyboard.press('v')
  const map = page.getByRole('complementary', { name: 'Passage map', exact: true })
  await expect(map.locator('.passage-list li')).toHaveCount(3)
  await map.getByLabel('Passage name', { exact: true }).fill('Opening in progress')
  await page.evaluate(() => window.__piano.player.seek(6))
  await expect(map.getByLabel('Passage name', { exact: true })).toHaveValue('Opening in progress')
  await map.getByRole('button', { name: 'Bars 1–2, played bars 4 to 5', exact: true }).click()
  expect(await page.evaluate(() => window.__piano.player.time)).toBe(6)
  await map.getByRole('button', { name: 'Loop passage', exact: true }).click()
  expect(await loop(page)).toEqual({ start: 6, end: 10 })
  await map.getByRole('button', { name: 'Loop end boundary', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  expect(await loop(page)).toEqual({ start: 6, end: 12 })
  await map.getByRole('button', { name: 'Loop start boundary', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  expect(await loop(page)).toEqual({ start: 8, end: 12 })
  expect(await page.evaluate(() => window.__piano.player.speed)).toBe(1)
  const start = (await map.getByRole('button', { name: 'Loop start boundary', exact: true }).boundingBox())!
  const overview = (await map.locator('.passage-overview').boundingBox())!
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(overview.x + overview.width * .52, start.y + start.height / 2, { steps: 4 })
  await page.mouse.up()
  expect(await loop(page)).toEqual({ start: 6, end: 12 })
  await map.getByLabel('Passage name', { exact: true }).fill('Return')
  await map.getByRole('button', { name: 'Save passage', exact: true }).click()
  await expect(map.locator('.passage-saved')).toContainText('Return')
  await expect(map.locator('.passage-saved')).toContainText('Bars 1–2 · Bar 4')
  await page.reload()
  await page.waitForFunction(() => window.__piano?.timeline?.sounds.length === 30)
  await page.keyboard.press('v')
  await map.locator('.passage-saved button', { hasText: 'Return' }).click()
  expect(await loop(page)).toEqual({ start: 6, end: 12 })
  expect(await page.evaluate(() => window.__piano.player.time)).toBe(6)
  await map.getByRole('button', { name: 'Release passage loop', exact: true }).click()
  expect(await loop(page)).toBeNull()
  expect(errors).toEqual([])
})

test('performance: key travel is visible and pointer release stops the touch voice', async ({ page }) => {
  await open(page)
  await page.keyboard.press('p')
  const key = page.locator('rect.key[data-note="60"]')
  const group = key.locator('..')
  const box = (await key.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height - 10)
  await page.mouse.down()
  await expect(key).toHaveClass(/pressed/)
  await expect(group).toHaveClass(/down/)
  await expect.poll(() => group.evaluate((el) => getComputedStyle(el).transform)).not.toBe('none')
  await expect.poll(() => page.evaluate(() => window.__piano.engine.piano?.activeVoices ?? 0)).toBe(1)
  await page.mouse.up()
  await expect(group).not.toHaveClass(/down/)
  await expect.poll(() => page.evaluate(() => window.__piano.engine.piano?.activeVoices ?? 0)).toBe(0)
})

test('performance: lighting changes the canvas, persists, and reduced motion removes decorative light', async ({ page }) => {
  await open(page)
  await page.keyboard.press('p')
  const canvas = page.getByRole('img', { name: 'Falling notes', exact: true })
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByLabel('Lighting', { exact: true }).fill('100')
  const lit = await canvas.evaluate((el) => (el as HTMLCanvasElement).toDataURL())
  await page.getByLabel('Lighting', { exact: true }).fill('0')
  await expect(page.getByTestId('keys')).toHaveAttribute('data-lighting', '0')
  const plain = await canvas.evaluate((el) => (el as HTMLCanvasElement).toDataURL())
  expect(plain).not.toBe(lit)
  await page.getByLabel('Lighting', { exact: true }).fill('80')
  await page.reload()
  await page.waitForFunction(() => !!window.__piano?.timeline)
  await expect(page.getByTestId('keys')).toHaveAttribute('data-lighting', '0.8')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.getByTestId('keys')).toHaveAttribute('data-lighting', '0')
  await page.keyboard.press('p')
  await page.getByRole('button', { name: 'Count-in', exact: true }).click()
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await page.evaluate(() => (document.activeElement as HTMLElement)?.blur())
  await page.waitForTimeout(2800)
  await expect(page.locator('.app')).not.toHaveClass(/controls-hidden/)
  await page.keyboard.press(' ')
})

